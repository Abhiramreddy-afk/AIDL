"""### 2. Preprocessing & Feature Engineering
We will now process the dataset:
1. Extract the brand name from `CarName` and correct spelling variations.
2. One-hot encode categorical features.
3. Separate independent variables ($X$) and the target variable ($y$, `price`).
4. Split the data into train and test sets.
5. Standardize the numerical features.
"""

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

# Create a copy to work on
data = df.copy()

# 1. Extract Brand from CarName
data['Brand'] = data['CarName'].apply(lambda x: x.split(' ')[0].lower())

# Fix brand spelling mistakes
brand_corrections = {
    'maxda': 'mazda',
    'vokswagen': 'volkswagen',
    'vw': 'volkswagen',
    'toyouta': 'toyota',
    'porcshz': 'porsche',
    'alfa-romero': 'alfaromeo'
}
data['Brand'] = data['Brand'].replace(brand_corrections)

# Drop car_ID and raw CarName as they aren't useful features directly
data = data.drop(columns=['car_ID', 'CarName'])

# Define numerical and categorical columns
num_cols = data.select_dtypes(include=['int64', 'float64']).columns.tolist()
if 'price' in num_cols:
    num_cols.remove('price')

cat_cols = data.select_dtypes(include=['object']).columns.tolist()

# 2. One-Hot Encoding
