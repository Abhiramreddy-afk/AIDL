X_test[num_cols] = scaler.transform(X_test[num_cols])

# Convert to numpy arrays for TensorFlow
X_train_arr = X_train.values
X_test_arr = X_test.values

print(f"Training set shape: {X_train_arr.shape}")
print(f"Testing set shape: {X_test_arr.shape}")

"""### 3. Model Development & Training (5 Deep Learning Algorithms)

We will define 5 distinct models using TensorFlow Keras, compile them using the Adam optimizer, and measure performance using Mean Absolute Error (MAE) and Root Mean Squared Error (RMSE).
"""

import tensorflow as tf
from tensorflow.keras import layers, Model
from sklearn.metrics import mean_absolute_error, mean_squared_error

input_dim = X_train_arr.shape[1]
results = {}

# Helper function to plot training history
def plot_history(history, title):
    plt.figure(figsize=(8, 4))
    plt.plot(history.history['loss'], label='Train Loss')
    plt.plot(history.history['val_loss'], label='Val Loss')
    plt.title(title)
    plt.xlabel('Epochs')
    plt.ylabel('MSE')
    plt.legend()
    plt.show()

# Helper function to evaluate models
def evaluate_model(model, name, X_test, y_test):
    predictions = model.predict(X_test).flatten()
    mae = mean_absolute_error(y_test, predictions)
    rmse = np.sqrt(mean_squared_error(y_test, predictions))
    results[name] = {'MAE': mae, 'RMSE': rmse}
    print(f"{name} - MAE: {mae:.2f}, RMSE: {rmse:.2f}")
    return predictions

# Common Training Parameters
epochs = 150
batch_size = 16
validation_split = 0.1
verbose = 0

# ==========================================================
# 1. Standard MLP (Multi-Layer Perceptron)
# ==========================================================

def build_standard_mlp():
    inputs = layers.Input(shape=(input_dim,))
    x = layers.Dense(128, activation='relu')(inputs)
    x = layers.Dense(64, activation='relu')(x)
    outputs = layers.Dense(1)(x)
    model = Model(inputs, outputs)
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    return model

model1 = build_standard_mlp()
hist1 = model1.fit(X_train_arr, y_train, epochs=epochs, batch_size=batch_size,
                  validation_split=validation_split, verbose=verbose)
plot_history(hist1, "Model 1: Standard MLP")
_ = evaluate_model(model1, "Standard MLP", X_test_arr, y_test)

# ==========================================================
# 2. Wide & Deep Network
# ==========================================================

def build_wide_and_deep():
    inputs = layers.Input(shape=(input_dim,))

    # Deep path
    deep = layers.Dense(64, activation='relu')(inputs)
    deep = layers.Dense(64, activation='relu')(deep)

    # Wide path concatenated with Deep path
    concat = layers.concatenate([inputs, deep])
    outputs = layers.Dense(1)(concat)

    model = Model(inputs, outputs)
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    return model

model2 = build_wide_and_deep()
hist2 = model2.fit(X_train_arr, y_train, epochs=epochs, batch_size=batch_size,
                  validation_split=validation_split, verbose=verbose)
plot_history(hist2, "Model 2: Wide & Deep Network")
_ = evaluate_model(model2, "Wide & Deep", X_test_arr, y_test)

# ==========================================================
# 3. Deep MLP with Dropout & Batch Normalization
# ==========================================================

def build_regularized_mlp():
    inputs = layers.Input(shape=(input_dim,))
    x = layers.Dense(128)(inputs)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)
    x = layers.Dropout(0.2)(x)

    x = layers.Dense(64)(x)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)
    x = layers.Dropout(0.2)(x)

    outputs = layers.Dense(1)(x)
    model = Model(inputs, outputs)
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    return model

model3 = build_regularized_mlp()
hist3 = model3.fit(X_train_arr, y_train, epochs=epochs, batch_size=batch_size,
                  validation_split=validation_split, verbose=verbose)
plot_history(hist3, "Model 3: Deep Regularized MLP")
_ = evaluate_model(model3, "Regularized MLP", X_test_arr, y_test)

# ==========================================================
# 4. Residual Connection Network (ResNet-like)
# ==========================================================

def build_resnet_mlp():
    inputs = layers.Input(shape=(input_dim,))

    # Linear projection to matching residual dimensionality
    proj = layers.Dense(64, activation='relu')(inputs)

    # Residual block 1
    x = layers.Dense(64, activation='relu')(proj)
    x = layers.Dense(64)(x)
    res1 = layers.add([proj, x])
    res1 = layers.Activation('relu')(res1)

    # Residual block 2
    y = layers.Dense(64, activation='relu')(res1)
    y = layers.Dense(64)(y)
    res2 = layers.add([res1, y])
    res2 = layers.Activation('relu')(res2)

    outputs = layers.Dense(1)(res2)
    model = Model(inputs, outputs)
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    return model

model4 = build_resnet_mlp()
hist4 = model4.fit(X_train_arr, y_train, epochs=epochs, batch_size=batch_size,
                  validation_split=validation_split, verbose=verbose)
plot_history(hist4, "Model 4: Residual Connection Network")
_ = evaluate_model(model4, "ResNet-like MLP", X_test_arr, y_test)

# ==========================================================
# 5. Feature Attention Network
# ==========================================================

def build_attention_mlp():
    inputs = layers.Input(shape=(input_dim,))

    # Feature encoding
    projection = layers.Dense(64, activation='relu')(inputs)

    # Multi-Head Attention layer representing tabular feature interaction
    # Query, Key, Value vectors projected from encoded representations
    q = layers.Dense(64)(projection)
    k = layers.Dense(64)(projection)
    v = layers.Dense(64)(projection)

    # Reshape vectors to fit MultiHeadAttention input dimension (batch, sequence_len, dimension)
    # We treat tabular features as 1D sequence of length 1 with depth 64
    q = layers.Reshape((1, 64))(q)
    k = layers.Reshape((1, 64))(k)
    v = layers.Reshape((1, 64))(v)

    attention = layers.MultiHeadAttention(num_heads=4, key_dim=16)(q, k, v)
    attention = layers.Flatten()(attention)

    x = layers.concatenate([layers.Flatten()(projection), attention])
    x = layers.Dense(32, activation='relu')(x)
    outputs = layers.Dense(1)(x)

    model = Model(inputs, outputs)
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    return model

model5 = build_attention_mlp()
hist5 = model5.fit(X_train_arr, y_train, epochs=epochs, batch_size=batch_size,
                  validation_split=validation_split, verbose=verbose)
plot_history(hist5, "Model 5: Feature Attention Network")
_ = evaluate_model(model5, "Attention MLP", X_test_arr, y_test)

